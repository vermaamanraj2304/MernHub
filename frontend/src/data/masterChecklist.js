export function getAllChecklistItems() {
  const items = [];
  coreModules.forEach((mod) => {
    mod.topics.forEach((topic) => {
      topic.items.forEach((item) => {
        items.push({
          ...item,
          category: 'Core Curriculum',
          moduleNumber: mod.number,
          moduleName: mod.name,
          badgeColor: mod.badgeColor,
          icon: mod.icon,
        });
      });
    });
  });

  deepDiveTracks.forEach((track) => {
    track.topics.forEach((topic) => {
      topic.items.forEach((item) => {
        items.push({
          ...item,
          category: 'Deep-Dive Tracks',
          moduleNumber: track.number,
          moduleName: track.name,
          badgeColor: track.badgeColor,
          icon: track.icon,
        });
      });
    });
  });

  return items;
}

export function getChecklistStats(completedIds = []) {
  const all = getAllChecklistItems();
  const completedCount = all.filter((i) => completedIds.includes(i.id)).length;
  const totalCount = all.length;
  const percentage = totalCount > 0 ? Math.round((completedCount / totalCount) * 100) : 0;

  return {
    totalCount,
    completedCount,
    percentage,
  };
}
